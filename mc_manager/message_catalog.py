class MessageText(str):
    def __new__(cls, key, values):
        instance = super().__new__(cls, EXTRA_MESSAGES[key].format_map(values))
        instance.key = key
        instance.values = values
        return instance

    def localize(self, settings, depth=0):
        return settings.render(self.key, _depth=depth + 1, limit=None, **self.values)

    def __add__(self, other):
        return join_text("", (self, other))

    def __radd__(self, other):
        return join_text("", (other, self))


class JoinedText(str):
    def __new__(cls, separator, parts):
        parts = tuple(parts)
        instance = super().__new__(cls, separator.join(map(str, parts)))
        instance.separator = separator
        instance.parts = parts
        return instance

    def localize(self, settings, depth=0):
        return self.separator.join(settings.localize(part, depth + 1) for part in self.parts)

    def __add__(self, other):
        return join_text("", (self, other))

    def __radd__(self, other):
        return join_text("", (other, self))


def text(key, **values):
    return MessageText(key, values)


def join_text(separator: str, parts: Iterable):
    return JoinedText(separator, parts)
